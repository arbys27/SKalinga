CREATE OR REPLACE FUNCTION public.skalinga_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.skalinga_set_updated_date()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_date = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS public.users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL,
    password_hash varchar(255) NOT NULL,
    member_id varchar(20) NOT NULL UNIQUE,
    status varchar(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive', 'suspended')),
    email_verified boolean NOT NULL DEFAULT false,
    email_verified_at timestamptz,
    phone_verified boolean NOT NULL DEFAULT false,
    phone_verified_at timestamptz,
    last_otp_verified_at timestamptz,
    last_login timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_lower ON public.users (lower(email));
CREATE INDEX IF NOT EXISTS idx_users_member_id ON public.users (member_id);
CREATE INDEX IF NOT EXISTS idx_users_status ON public.users (status);

CREATE TABLE IF NOT EXISTS public.youth_profiles (
