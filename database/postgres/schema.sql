CREATE OR REPLACE VIEW public.active_users_by_barangay
WITH (security_invoker = true)
AS
SELECT yp.barangay,
       count(u.id) AS active_count,
       count(DISTINCT yp.gender) AS gender_diversity
FROM public.users AS u
JOIN public.youth_profiles AS yp ON yp.user_id = u.id
WHERE u.status = 'active'
GROUP BY yp.barangay;

CREATE OR REPLACE VIEW public.user_profiles_full
WITH (security_invoker = true)
AS
SELECT u.id,
       u.email,
       u.member_id,
       u.status,
       u.created_at AS user_created_at,
       yp.firstname,
       yp.lastname,
       yp.birthday,
       yp.age,
       yp.gender,
       yp.phone,
       yp.address,
       yp.barangay,
       yp.avatar_path,
       yp.bio,
       yp.updated_at AS profile_updated_at
FROM public.users AS u
LEFT JOIN public.youth_profiles AS yp ON yp.user_id = u.id;

