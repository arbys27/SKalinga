-- Public disclosure documents. Safe to run repeatedly.

CREATE TABLE IF NOT EXISTS public.public_disclosures (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    category varchar(50) NOT NULL DEFAULT 'Other'
        CHECK (category IN ('Budget and Finance', 'Programs and Projects', 'Memos and Resolutions', 'Other')),
    fiscal_year smallint,
    description text,
    original_name varchar(255) NOT NULL,
    file_path varchar(255) NOT NULL,
    mime_type varchar(100) NOT NULL,
    file_size bigint NOT NULL CHECK (file_size >= 0),
    status varchar(20) NOT NULL DEFAULT 'Published' CHECK (status IN ('Draft', 'Published')),
    created_by integer REFERENCES public.admins(id) ON UPDATE CASCADE ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_public_disclosures_status
    ON public.public_disclosures (status);
CREATE INDEX IF NOT EXISTS idx_public_disclosures_category
    ON public.public_disclosures (category);
CREATE INDEX IF NOT EXISTS idx_public_disclosures_fiscal_year
    ON public.public_disclosures (fiscal_year);

DROP TRIGGER IF EXISTS public_disclosures_set_updated_at ON public.public_disclosures;
CREATE TRIGGER public_disclosures_set_updated_at
BEFORE UPDATE ON public.public_disclosures
FOR EACH ROW EXECUTE FUNCTION public.skalinga_set_updated_at();

ALTER TABLE public.public_disclosures ENABLE ROW LEVEL SECURITY;
