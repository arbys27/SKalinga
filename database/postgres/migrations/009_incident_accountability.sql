-- Incident handler assignment and immutable status/action history.
-- Safe to run repeatedly.

ALTER TABLE public.incidents
    ADD COLUMN IF NOT EXISTS assigned_to integer
        REFERENCES public.admins(id) ON UPDATE CASCADE ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS handler_name text,
    ADD COLUMN IF NOT EXISTS resolved_at timestamptz,
    ADD COLUMN IF NOT EXISTS closed_at timestamptz,
    ADD COLUMN IF NOT EXISTS resolution_notes text;

CREATE INDEX IF NOT EXISTS idx_incidents_assigned_to
    ON public.incidents (assigned_to);

CREATE TABLE IF NOT EXISTS public.incident_status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id integer NOT NULL REFERENCES public.incidents(id) ON DELETE CASCADE,
    old_status varchar(20) NOT NULL,
    new_status varchar(20) NOT NULL,
    changed_by integer REFERENCES public.admins(id) ON UPDATE CASCADE ON DELETE SET NULL,
    changed_by_name text NOT NULL,
    notes text,
    old_assigned_to integer REFERENCES public.admins(id) ON UPDATE CASCADE ON DELETE SET NULL,
    old_handler_name text,
    new_assigned_to integer REFERENCES public.admins(id) ON UPDATE CASCADE ON DELETE SET NULL,
    new_handler_name text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_incident_status_history_incident_created
    ON public.incident_status_history (incident_id, created_at, id);
CREATE INDEX IF NOT EXISTS idx_incident_status_history_changed_by_created
    ON public.incident_status_history (changed_by, created_at DESC);

ALTER TABLE public.incident_status_history ENABLE ROW LEVEL SECURITY;
