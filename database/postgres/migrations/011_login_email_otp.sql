CREATE TABLE IF NOT EXISTS public.login_challenges (
    id uuid PRIMARY KEY,
    user_type varchar(20) NOT NULL
        CHECK (user_type IN ('youth', 'admin', 'sk_official')),
    user_id integer NOT NULL,
    token_hash char(64) NOT NULL,
    code_hash char(64) NOT NULL,
    expires_at timestamptz NOT NULL,
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    max_attempts integer NOT NULL DEFAULT 5 CHECK (max_attempts > 0),
    send_count integer NOT NULL DEFAULT 1 CHECK (send_count > 0),
    last_sent_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ip varchar(45) NOT NULL,
    user_agent text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    consumed_at timestamptz,
    redirect_to varchar(120),
    remember_device boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS idx_login_challenges_token_hash
    ON public.login_challenges (token_hash);
CREATE INDEX IF NOT EXISTS idx_login_challenges_expires_at
    ON public.login_challenges (expires_at);
CREATE INDEX IF NOT EXISTS idx_login_challenges_user_created
    ON public.login_challenges (user_type, user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_login_challenges_ip_created
    ON public.login_challenges (ip, created_at);

ALTER TABLE public.login_challenges ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.trusted_devices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_type varchar(20) NOT NULL DEFAULT 'youth' CHECK (user_type = 'youth'),
    user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    token_hash char(64) NOT NULL UNIQUE,
    user_agent_hash char(64) NOT NULL,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_trusted_devices_user
    ON public.trusted_devices (user_id, expires_at);
ALTER TABLE public.trusted_devices ENABLE ROW LEVEL SECURITY;
