-- Masterlist activation and rate-limit storage. Safe to run repeatedly.

CREATE TABLE IF NOT EXISTS public.kk_masterlist (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voter_id varchar(100) NOT NULL,
    first_name varchar(100) NOT NULL,
    last_name varchar(100) NOT NULL,
    middle_name varchar(100),
    birthday date NOT NULL,
    age smallint NOT NULL,
    sex varchar(30) NOT NULL,
    address text NOT NULL,
    purok_or_barangay varchar(150) NOT NULL,
    is_claimed boolean NOT NULL DEFAULT false,
    claimed_by_user_id integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_kk_masterlist_voter_id UNIQUE (voter_id),
    CONSTRAINT fk_kk_masterlist_claimed_user
        FOREIGN KEY (claimed_by_user_id) REFERENCES public.users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_kk_masterlist_name ON public.kk_masterlist (last_name, first_name);
CREATE INDEX IF NOT EXISTS idx_kk_masterlist_claimed ON public.kk_masterlist (is_claimed);
CREATE UNIQUE INDEX IF NOT EXISTS uq_kk_masterlist_voter_id_lower
    ON public.kk_masterlist (lower(voter_id));

CREATE TABLE IF NOT EXISTS public.login_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_address varchar(45) NOT NULL,
    attempt_type varchar(50) NOT NULL,
    attempted_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_login_attempts_lookup
    ON public.login_attempts (ip_address, attempt_type, attempted_at);

ALTER TABLE public.users ALTER COLUMN email DROP NOT NULL;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS masterlist_id integer;
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_masterlist_id ON public.users (masterlist_id);
ALTER TABLE public.youth_profiles ALTER COLUMN phone SET NOT NULL;
ALTER TABLE public.youth_profiles ADD COLUMN IF NOT EXISTS phone_changed_at timestamptz;

DO $migration$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_users_masterlist_id'
          AND conrelid = 'public.users'::regclass
    ) THEN
        ALTER TABLE public.users
            ADD CONSTRAINT fk_users_masterlist_id
            FOREIGN KEY (masterlist_id) REFERENCES public.kk_masterlist(id)
            ON DELETE RESTRICT;
    END IF;
END
$migration$;

ALTER TABLE public.kk_masterlist ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.login_attempts ENABLE ROW LEVEL SECURITY;
