-- One-time service verification tokens. Safe to run repeatedly.

CREATE TABLE IF NOT EXISTS public.service_verification_settings (
    service_type text PRIMARY KEY,
    token_ttl_seconds integer NOT NULL DEFAULT 180
        CHECK (token_ttl_seconds BETWEEN 120 AND 300),
    otp_required boolean NOT NULL DEFAULT false,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO public.service_verification_settings (service_type, token_ttl_seconds, otp_required)
VALUES ('print', 180, false)
ON CONFLICT (service_type) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.service_verification_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    service_type text NOT NULL,
    service_ref text NOT NULL,
    token_hash char(64) NOT NULL UNIQUE,
    status text NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'used', 'expired', 'cancelled')),
    expires_at timestamptz NOT NULL,
    used_at timestamptz,
    scanned_by_admin_id integer REFERENCES public.admins(id) ON DELETE SET NULL,
    otp_required boolean NOT NULL DEFAULT false,
    otp_hash char(64),
    otp_expires_at timestamptz,
    otp_attempts smallint NOT NULL DEFAULT 0 CHECK (otp_attempts BETWEEN 0 AND 5),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_service_verification_tokens_status_expiry
    ON public.service_verification_tokens (status, expires_at);
CREATE INDEX IF NOT EXISTS idx_service_verification_tokens_user_created
    ON public.service_verification_tokens (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_service_verification_tokens_service_ref
    ON public.service_verification_tokens (service_type, service_ref);

CREATE TABLE IF NOT EXISTS public.service_verification_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_id bigint REFERENCES public.service_verification_tokens(id) ON DELETE SET NULL,
    token_hash char(64),
    user_id integer REFERENCES public.users(id) ON DELETE SET NULL,
    admin_id integer REFERENCES public.admins(id) ON DELETE SET NULL,
    action text NOT NULL,
    result text NOT NULL,
    service_type text,
    service_ref text,
    ip_address varchar(45) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_service_verification_audit_created
    ON public.service_verification_audit (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_service_verification_audit_admin
    ON public.service_verification_audit (admin_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_service_verification_audit_user
    ON public.service_verification_audit (user_id, created_at DESC);

ALTER TABLE public.printing_requests
    DROP CONSTRAINT IF EXISTS printing_requests_status_check;
ALTER TABLE public.printing_requests
    ADD CONSTRAINT printing_requests_status_check
        CHECK (status IN ('Pending', 'Printing', 'Completed', 'Claimed', 'Rejected'));

ALTER TABLE public.service_verification_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.service_verification_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.service_verification_audit ENABLE ROW LEVEL SECURITY;
