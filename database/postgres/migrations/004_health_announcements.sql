-- Health announcements. Safe to run repeatedly.

CREATE TABLE IF NOT EXISTS public.health_announcements (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    category varchar(100) NOT NULL CHECK (category IN (
        'Dental Caravan',
        'Medical Mission',
        'Vaccination',
        'Free Check-up',
        'Mental Health',
        'Nutrition and Fitness',
        'Blood Donation',
        'Other'
    )),
    description text,
    event_date date NOT NULL,
    start_time time,
    end_time time,
    venue varchar(255),
    slots integer,
    requirements text,
    image_path varchar(255),
    status varchar(20) NOT NULL DEFAULT 'Draft'
        CHECK (status IN ('Draft', 'Published', 'Cancelled', 'Archived')),
    published_at timestamp,
    created_by integer REFERENCES public.admins(id) ON UPDATE CASCADE ON DELETE SET NULL,
    updated_by integer REFERENCES public.admins(id) ON UPDATE CASCADE ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_health_announcements_status
    ON public.health_announcements (status);
CREATE INDEX IF NOT EXISTS idx_health_announcements_event_date
    ON public.health_announcements (event_date);

DROP TRIGGER IF EXISTS health_announcements_set_updated_at ON public.health_announcements;
CREATE TRIGGER health_announcements_set_updated_at
BEFORE UPDATE ON public.health_announcements
FOR EACH ROW EXECUTE FUNCTION public.skalinga_set_updated_at();

