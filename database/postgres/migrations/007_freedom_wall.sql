-- Moderated youth Freedom Wall. Safe to run repeatedly.

CREATE TABLE IF NOT EXISTS public.freedom_wall_posts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    category varchar(20) NOT NULL
        CHECK (category IN ('Feedback', 'Suggestion', 'Concern', 'Other')),
    title varchar(120) NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 120),
    body text NOT NULL CHECK (char_length(btrim(body)) BETWEEN 1 AND 2000),
    is_anonymous boolean NOT NULL DEFAULT false,
    status varchar(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    rejection_reason text,
    moderated_by integer REFERENCES public.admins(id) ON DELETE SET NULL,
    approved_by integer REFERENCES public.admins(id) ON DELETE SET NULL,
    moderated_at timestamptz,
    approved_at timestamptz,
    is_hidden boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_freedom_wall_posts_status
    ON public.freedom_wall_posts (status);
CREATE INDEX IF NOT EXISTS idx_freedom_wall_posts_created_at
    ON public.freedom_wall_posts (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_freedom_wall_posts_user_id
    ON public.freedom_wall_posts (user_id);

DROP TRIGGER IF EXISTS freedom_wall_posts_set_updated_at ON public.freedom_wall_posts;
CREATE TRIGGER freedom_wall_posts_set_updated_at
BEFORE UPDATE ON public.freedom_wall_posts
FOR EACH ROW EXECUTE FUNCTION public.skalinga_set_updated_at();

ALTER TABLE public.freedom_wall_posts ENABLE ROW LEVEL SECURITY;
